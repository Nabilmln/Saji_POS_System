import { test, expect, signIn, guestOrder, call } from "./fixtures";
import AxeBuilder from "@axe-core/playwright";

test("two guests share one bill, stale review stops payment, and a lost response replays once", async ({ browser, page, data }, testInfo) => {
  const first = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const second = await browser.newContext({ viewport: { width: 360, height: 800 } });
  const alice = await first.newPage(), bob = await second.newPage();
  await guestOrder(alice, data.token, "Aulia", data.menuName);
  await guestOrder(bob, data.token, "Budi", data.menuName);
  for (const target of [alice, bob]) expect((await new AxeBuilder({ page: target }).analyze()).violations).toEqual([]);
  await alice.screenshot({ path: testInfo.outputPath("customer-status.png"), fullPage: true });
  await expect(alice.getByRole("heading", { name: "Budi", exact: true })).toHaveCount(0);
  await expect(bob.getByRole("heading", { name: "Aulia", exact: true })).toHaveCount(0);
  expect((await data.pool.query("SELECT count(*)::int AS n FROM table_sessions WHERE table_id=$1", [data.tableId])).rows[0].n).toBe(1);
  await signIn(page);
  await page.goto(`/pos/tables/${data.tableId}`);
  await expect(page.getByRole("button", { name: "Konfirmasi", exact: true })).toHaveCount(2);
  await page.getByRole("button", { name: "Konfirmasi", exact: true }).first().click();
  await expect(page.getByRole("checkbox", { name: /Sudah disajikan/ })).toHaveCount(1);
  await page.getByRole("checkbox", { name: /Sudah disajikan/ }).click();
  await expect(page.getByRole("checkbox", { name: /Sudah disajikan/ })).toBeChecked();
  await page.getByRole("button", { name: "Konfirmasi", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: /Sudah disajikan/ })).toHaveCount(2);
  await page.getByRole("checkbox", { name: /Sudah disajikan/ }).nth(1).click();
  await expect(page.getByRole("checkbox", { name: /Sudah disajikan/ }).nth(1)).toBeChecked();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("cashier-orders-right.png"), fullPage: true });
  await page.getByRole("link", { name: "Lihat tagihan & pembayaran" }).click();
  await page.getByLabel("Uang diterima (Rp)").fill("1");
  await page.getByRole("checkbox", { name: /Saya sudah memeriksa/ }).check();
  await expect(page.getByRole("button", { name: "Konfirmasi pembayaran", exact: true })).toBeDisabled();
  await page.getByLabel("Uang diterima (Rp)").fill("100000");
  await page.getByRole("button", { name: "Konfirmasi pembayaran", exact: true }).click();
  await data.pool.query("UPDATE store_settings SET tax_enabled=true,tax_rate_bps=1000,version=version+1 WHERE id=1");
  await page.getByRole("button", { name: "Bayar tunai", exact: true }).click();
  await expect(page.getByText("Tagihan berubah. Periksa total terbaru dan konfirmasi ulang.", { exact: true })).toBeVisible();
  await expect(page.getByRole("checkbox", { name: /Saya sudah memeriksa/ })).not.toBeChecked();
  await expect(page.getByRole("button", { name: "Konfirmasi pembayaran", exact: true })).toBeDisabled();
  await page.getByRole("checkbox", { name: /Saya sudah memeriksa/ }).check();
  await page.getByRole("button", { name: "Konfirmasi pembayaran", exact: true }).click();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("cashier-payment.png"), fullPage: true });
  await page.route("**/api/staff/table-sessions/*/payments", async (route) => { await route.fetch(); await route.abort("failed"); }, { times: 1 });
  await page.getByRole("button", { name: "Bayar tunai", exact: true }).click();
  await expect(page.getByRole("button", { name: "Ulangi transaksi yang sama" })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Ulangi transaksi yang sama" }).click();
  await expect(page.getByRole("heading", { name: "Pembayaran berhasil" })).toBeVisible();
  expect((await data.pool.query("SELECT count(*)::int AS n FROM payments p JOIN table_sessions s ON s.id=p.session_id WHERE s.table_id=$1", [data.tableId])).rows[0].n).toBe(1);
  await page.getByRole("link", { name: "Lihat struk digital" }).click();
  await expect(page.getByText("Lunas", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("cashier-receipt-mobile.png"), fullPage: true });
  const receiptBefore = await page.locator(".pos-receipt").innerText();
  await data.pool.query("UPDATE store_settings SET tax_enabled=false,version=version+1 WHERE id=1");
  await data.pool.query("UPDATE menu_items SET price_idr=99999 WHERE id=$1", [data.menuId]);
  await page.reload();
  await expect(page.locator(".pos-receipt")).toHaveText(receiptBefore, { useInnerText: true });
  expect((await data.pool.query("SELECT status FROM dining_tables WHERE id=$1", [data.tableId])).rows[0].status).toBe("AVAILABLE");
  await first.close(); await second.close();
});

test("manual order can be voided with a reason and closed without a payment", async ({ page, data }) => {
  await signIn(page);
  await page.goto(`/pos/tables/${data.tableId}`);
  await page.getByRole("button", { name: "Tambah order manual" }).click();
  await page.getByLabel("Nama pelanggan / label").fill("Tamu manual");
  await page.getByRole("button", { name: `Tambah ${data.menuName}`, exact: true }).click();
  await page.getByRole("button", { name: "Simpan order Menunggu" }).click();
  await page.getByRole("button", { name: "Konfirmasi", exact: true }).click();
  await page.getByRole("checkbox", { name: /Sudah disajikan/ }).click();
  await expect(page.getByRole("checkbox", { name: /Sudah disajikan/ })).toBeChecked();
  await page.getByRole("button", { name: "Batalkan item", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("Hanya dapat dibatalkan karena kesalahan pegawai");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Batalkan item", exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Batalkan item", exact: true }).click();
  await page.getByLabel("Penjelasan").fill("Pegawai salah memasukkan pesanan");
  await page.getByRole("dialog").getByRole("button", { name: "Batalkan item", exact: true }).click();
  await page.getByRole("button", { name: "Tutup sesi tanpa pembayaran" }).click();
  await page.getByLabel("Alasan penutupan").fill("Seluruh pesanan salah input");
  await page.getByRole("button", { name: "Tutup sesi", exact: true }).click();
  await expect(page.getByText("Belum ada pesanan pada sesi ini.")).toBeVisible();
  expect((await data.pool.query("SELECT closure_reason FROM table_sessions WHERE table_id=$1", [data.tableId])).rows[0].closure_reason).toBe("ALL_VOID");
  expect((await data.pool.query("SELECT count(*)::int AS n FROM payments p JOIN table_sessions s ON s.id=p.session_id WHERE s.table_id=$1", [data.tableId])).rows[0].n).toBe(0);
});

test("polling reconnects and anonymous, cashier, and inactive access remain guarded", async ({ page, data, context }) => {
  await page.goto("/admin/menus"); await expect(page.getByRole("heading", { name: "Masuk diperlukan" })).toBeVisible();
  await signIn(page); await page.goto(`/pos/tables/${data.tableId}`);
  await expect(page.getByRole("heading", { name: `Meja ${data.tableNumber}`, exact: true })).toBeVisible();
  await context.setOffline(true);
  await expect(page.locator(".inline-alert[role=alert]")).toContainText("belum tersinkron");
  await context.setOffline(false);
  await page.getByRole("button", { name: "Segarkan", exact: true }).first().click();
  await expect(page.locator(".inline-alert[role=alert]")).toHaveCount(0);
  expect((await call(page.request, "/admin/staff")).status()).toBe(403);
  await page.goto("/admin/staff"); await expect(page.getByRole("heading", { name: "Akses ditolak" })).toBeVisible();
  await data.pool.query("UPDATE staff_profiles SET is_active=false WHERE user_id='00000000-0000-4000-8000-000000000002'");
  expect((await call(page.request, "/staff/me")).status()).toBe(403);
  expect((await page.request.post("/api/staff/reservations", { headers: { Origin: "https://untrusted.example" }, data: {} })).status()).toBe(403);
});
