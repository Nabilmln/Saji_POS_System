import AxeBuilder from "@axe-core/playwright";
import { test, expect, signIn } from "./fixtures";

test("cashier calendar validates typed dates, navigates leap days and dismisses accessibly", async ({ page }, testInfo) => {
  await signIn(page);
  const field = page.getByRole("combobox", { name: "Tanggal", exact: true });
  await field.fill("31 Feb 2028");
  await expect(field).toHaveAttribute("aria-invalid", "true");
  expect(await field.evaluate((element) => (element as HTMLInputElement).checkValidity())).toBe(false);
  await field.fill("15 Oktober 2026");
  await field.press("Tab");
  await expect(field).toHaveValue("15 Okt 2026");
  await page.getByRole("button", { name: "English", exact: true }).click();
  const englishField = page.getByRole("combobox", { name: "Date", exact: true });
  await expect(englishField).toHaveValue("15 Oct 2026");
  await englishField.fill("2028-02-29");
  await englishField.press("ArrowDown");
  const calendar = page.getByRole("dialog", { name: "Choose date: Date", exact: true });
  await expect(calendar).toBeVisible();
  await expect(calendar.locator('[data-date="2028-02-29"]')).toBeFocused();
  await page.keyboard.press("ArrowRight");
  await expect(calendar.locator('[data-date="2028-03-01"]')).toBeFocused();
  await page.keyboard.press("ArrowLeft");
  await page.keyboard.press("PageDown");
  await expect(calendar.locator('[data-date="2028-03-29"]')).toBeFocused();
  await page.keyboard.press("Shift+PageUp");
  await page.keyboard.press("PageUp");
  await expect(calendar.locator('[data-date="2027-02-28"]')).toBeFocused();
  const filtered = page.waitForRequest((request) => request.url().includes("/api/staff/orders?") && new URL(request.url()).searchParams.get("date") === "2027-02-28");
  await page.keyboard.press("Enter");
  await filtered;
  await expect(calendar).toBeHidden();
  await expect(englishField).toHaveValue("28 Feb 2027");
  await page.getByRole("button", { name: "Open calendar: Date", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(calendar).toBeHidden();
  expect(await page.locator(".date-input-wrap").evaluate((element) => element.contains(document.activeElement))).toBe(true);
  await page.getByRole("button", { name: "Open calendar: Date", exact: true }).click();
  await page.getByLabel("Search tables", { exact: true }).click();
  await expect(calendar).toBeHidden();
  for (const width of [1440, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.getByRole("button", { name: "Open calendar: Date", exact: true }).click();
    const bounds = await calendar.boundingBox();
    expect(bounds!.x).toBeGreaterThanOrEqual(0);
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width);
    expect(bounds!.y).toBeGreaterThanOrEqual(0);
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844);
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await page.screenshot({ path: testInfo.outputPath(`calendar-${width}.png`), fullPage: true });
    await page.keyboard.press("Escape");
  }
  await page.getByRole("button", { name: "Open calendar: Date", exact: true }).click();
  const cleared = page.waitForRequest((request) => request.url().includes("/api/staff/orders?") && !new URL(request.url()).searchParams.has("date"));
  await calendar.getByRole("button", { name: "Clear", exact: true }).click();
  await cleared;
  await expect(englishField).toHaveValue("");
});

test("report range calendars preserve ISO queries and required/invalid range validation", async ({ page }, testInfo) => {
  await signIn(page, "admin");
  await page.getByRole("radio", { name: "Kustom", exact: true }).check();
  const from = page.getByRole("combobox", { name: "Dari tanggal", exact: true });
  const to = page.getByRole("combobox", { name: "Sampai tanggal", exact: true });
  await from.fill("2026-10-01"); await to.fill("2026-10-15");
  await page.getByRole("button", { name: "Buka kalender: Sampai tanggal", exact: true }).click();
  const calendar = page.getByRole("dialog", { name: "Pilih tanggal: Sampai tanggal", exact: true });
  await calendar.getByRole("button", { name: "Bulan berikutnya", exact: true }).click();
  await calendar.locator('[data-date="2026-11-05"]').click();
  await expect(to).toHaveValue("5 Nov 2026");
  const report = page.waitForResponse((response) => response.url().includes("/api/admin/reports/revenue?") && new URL(response.url()).searchParams.get("from") === "2026-10-01" && new URL(response.url()).searchParams.get("to") === "2026-11-05");
  await page.getByRole("button", { name: "Tampilkan laporan", exact: true }).click();
  expect((await report).status()).toBe(200);
  await expect(from).toBeEnabled();
  await from.fill("");
  await page.getByRole("button", { name: "Tampilkan laporan", exact: true }).click();
  expect(await from.evaluate((element) => (element as HTMLInputElement).validity.valueMissing)).toBe(true);
  await from.fill("2026-11-06");
  await page.getByRole("button", { name: "Tampilkan laporan", exact: true }).click();
  await expect(page.locator(".inline-alert[role=alert]")).toContainText("Pilih rentang tanggal yang valid");
  await page.getByRole("button", { name: "English", exact: true }).click();
  await page.getByRole("button", { name: "Open calendar: From date", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Choose date: From date", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("report-calendar-en.png"), fullPage: true });
});

test("transaction date filters use the same calendar and preserve range guards", async ({ page }) => {
  await signIn(page); await page.goto("/pos/transactions");
  await page.getByRole("button", { name: "English", exact: true }).click();
  const from = page.getByRole("combobox", { name: "From date", exact: true });
  const to = page.getByRole("combobox", { name: "To date", exact: true });
  const filtered = page.waitForResponse((response) => response.url().includes("/api/staff/payments?") && new URL(response.url()).searchParams.get("from") === "2026-10-15");
  await from.fill("15 October 2026"); await from.press("Tab");
  expect((await filtered).status()).toBe(200);
  await expect(from).toHaveValue("15 Oct 2026");
  await to.fill("14 Oct 2026");
  await expect(page.locator(".inline-alert[role=alert]")).toContainText("The start date must not be after the end date.");
  await page.getByRole("button", { name: "Open calendar: To date", exact: true }).click();
  await page.getByRole("dialog", { name: "Choose date: To date", exact: true }).locator('[data-date="2026-10-16"]').click();
  await expect(page.locator(".inline-alert[role=alert]")).toHaveCount(0);
  await expect(to).toHaveValue("16 Oct 2026");
});

test("reservation calendar submits the chosen date and time unchanged in WIB", async ({ page, data }, testInfo) => {
  await signIn(page); await page.goto("/pos/reservations");
  await page.getByRole("button", { name: "Tambah reservasi", exact: true }).click();
  await page.getByLabel("Nama pelanggan", { exact: true }).fill("Calendar guest");
  await page.getByLabel("Kontak pelanggan", { exact: true }).fill("08123456789");
  await page.getByRole("combobox", { name: "Meja tersedia", exact: true }).click();
  await page.getByRole("option", { name: `Meja ${data.tableNumber}`, exact: true }).click();
  const field = page.getByRole("combobox", { name: "Waktu reservasi (WIB)", exact: true });
  await page.getByRole("button", { name: "Simpan reservasi", exact: true }).click();
  expect(await field.evaluate((element) => (element as HTMLInputElement).validity.valueMissing)).toBe(true);
  await page.getByRole("button", { name: "Buka kalender: Waktu reservasi (WIB)", exact: true }).click();
  const calendar = page.getByRole("dialog", { name: "Pilih tanggal: Waktu reservasi (WIB)", exact: true });
  const tomorrow = await page.evaluate(() => {
    const parts = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Jakarta", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date(Date.now() + 86400000));
    return parts;
  });
  await calendar.locator(`[data-date="${tomorrow}"]`).click();
  await calendar.getByLabel("Waktu (WIB)", { exact: true }).fill("19:30:30");
  await expect(calendar.getByRole("button", { name: "Terapkan", exact: true })).toBeDisabled();
  await calendar.getByLabel("Waktu (WIB)", { exact: true }).fill("19:30");
  await page.setViewportSize({ width: 390, height: 844 });
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("reservation-calendar-id.png"), fullPage: true });
  await calendar.getByRole("button", { name: "Terapkan", exact: true }).click();
  const saved = page.waitForResponse((response) => response.url().endsWith("/api/staff/reservations") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Simpan reservasi", exact: true }).click();
  const response = await saved;
  expect(response.request().postDataJSON().reservedFor).toBe(`${tomorrow}T19:30:00+07:00`);
  expect(response.status()).toBe(201);
  await expect(page.getByRole("row").filter({ hasText: "Calendar guest" })).toBeVisible();
});
